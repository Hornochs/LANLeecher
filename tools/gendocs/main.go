// Command gendocs generates documentation from the source:
//
//   - docs/configuration.md   reference of every config.yaml key
//   - docs/config.schema.json JSON Schema of config.yaml for editors
//   - docs/llms-full.txt      llms.txt, concepts, API guide, configuration and
//     the OpenAPI spec in one file, to paste into a prompt
//
// Field descriptions come from the doc comments in internal/config/config.go,
// defaults from config.Default(). Run from the repository root:
//
//	go run ./tools/gendocs          # write the files
//	go run ./tools/gendocs -check   # fail if they are out of date
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"time"

	"github.com/lan-dot-party/lanleecher/internal/config"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "only check that the generated files are up to date")
	flag.Parse()

	files, err := Generate(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
	stale := false
	for _, f := range files {
		path := filepath.Join(*root, f.Path)
		old, _ := os.ReadFile(path)
		if bytes.Equal(old, f.Content) {
			continue
		}
		if *check {
			fmt.Fprintf(os.Stderr, "%s is out of date; run: go run ./tools/gendocs\n", f.Path)
			stale = true
			continue
		}
		if err := os.WriteFile(path, f.Content, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "gendocs:", err)
			os.Exit(1)
		}
		fmt.Println("wrote", f.Path)
	}
	if stale {
		os.Exit(1)
	}
}

// File is one generated file.
type File struct {
	Path    string
	Content []byte
}

// field is one config key.
type field struct {
	Key     string // yaml name
	Doc     string
	Type    string // string, int, float, bool, duration, []string, or a struct name
	Enum    []string
	Default any
	Fields  []field // for nested structs
}

// Generate builds all generated files from the sources under root.
func Generate(root string) ([]File, error) {
	fields, err := configFields(filepath.Join(root, "internal/config/config.go"))
	if err != nil {
		return nil, err
	}
	reference := configReference(fields)
	schema, err := configSchema(fields)
	if err != nil {
		return nil, err
	}
	var full bytes.Buffer
	full.WriteString("# LANLeecher – complete documentation for LLMs\n\n")
	full.WriteString("This file is generated by `go run ./tools/gendocs`. It contains llms.txt, the concepts,\n")
	full.WriteString("the API guide, the configuration reference and the OpenAPI specification.\n")
	for _, part := range []struct {
		path    string
		content []byte
	}{
		{"llms.txt", nil},
		{"docs/concepts.md", nil},
		{"docs/api.md", nil},
		{"docs/configuration.md", reference},
		{"internal/api/openapi.yaml", nil},
	} {
		content := part.content
		if content == nil {
			if content, err = os.ReadFile(filepath.Join(root, part.path)); err != nil {
				return nil, err
			}
		}
		fmt.Fprintf(&full, "\n\n======== %s ========\n\n", part.path)
		full.Write(bytes.TrimSpace(content))
		full.WriteByte('\n')
	}
	return []File{
		{"docs/configuration.md", reference},
		{"docs/config.schema.json", schema},
		{"docs/llms-full.txt", full.Bytes()},
	}, nil
}

// configFields parses the Config struct and its nested structs.
func configFields(path string) ([]field, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	structs := map[string]*ast.StructType{}
	ast.Inspect(f, func(n ast.Node) bool {
		if ts, ok := n.(*ast.TypeSpec); ok {
			if st, ok := ts.Type.(*ast.StructType); ok {
				structs[ts.Name.Name] = st
			}
		}
		return true
	})
	defaults := reflect.ValueOf(config.Default()).Elem()
	var walk func(name string, def reflect.Value) ([]field, error)
	walk = func(name string, def reflect.Value) ([]field, error) {
		st, ok := structs[name]
		if !ok {
			return nil, fmt.Errorf("struct %s not found", name)
		}
		var out []field
		for _, af := range st.Fields.List {
			if af.Tag == nil || len(af.Names) == 0 {
				continue
			}
			tag := reflect.StructTag(strings.Trim(af.Tag.Value, "`"))
			key := strings.Split(tag.Get("yaml"), ",")[0]
			if key == "" || key == "-" {
				continue
			}
			fd := field{Key: key, Doc: cleanDoc(af.Names[0].Name, af.Doc.Text())}
			if e := tag.Get("enum"); e != "" {
				fd.Enum = strings.Split(e, ",")
			}
			value := def.FieldByName(af.Names[0].Name)
			switch t := af.Type.(type) {
			case *ast.Ident:
				if _, nested := structs[t.Name]; nested {
					fd.Type = t.Name
					if fd.Fields, err = walk(t.Name, value); err != nil {
						return nil, err
					}
				} else {
					fd.Type = goType(t.Name)
				}
			case *ast.SelectorExpr:
				if t.Sel.Name == "Duration" {
					fd.Type = "duration"
				}
			case *ast.ArrayType:
				fd.Type = "[]string"
			}
			if fd.Fields == nil {
				fd.Default = value.Interface()
			}
			out = append(out, fd)
		}
		return out, nil
	}
	return walk("Config", defaults)
}

func goType(name string) string {
	switch name {
	case "int":
		return "int"
	case "float64":
		return "float"
	case "bool":
		return "bool"
	}
	return "string"
}

// cleanDoc turns a Go doc comment into a description for users: lines are
// joined and the leading field name is dropped ("Path is the SQLite database
// file." -> "The SQLite database file.").
func cleanDoc(name, s string) string {
	words := strings.Fields(s)
	if len(words) > 1 && words[0] == name {
		words = words[1:]
		if words[0] == "is" || words[0] == "are" {
			words = words[1:]
		}
		if len(words) > 0 {
			words[0] = strings.ToUpper(words[0][:1]) + words[0][1:]
		}
	}
	return strings.Join(words, " ")
}

func formatDefault(v any) string {
	switch x := v.(type) {
	case time.Duration:
		switch {
		case x != 0 && x%time.Hour == 0:
			return fmt.Sprintf("%dh", x/time.Hour)
		case x != 0 && x%time.Minute == 0:
			return fmt.Sprintf("%dm", x/time.Minute)
		}
		return x.String()
	case []string:
		return "[" + strings.Join(x, ", ") + "]"
	case string:
		if x == "" {
			return "–"
		}
		return x
	case nil:
		return "–"
	}
	return fmt.Sprint(v)
}

func configReference(fields []field) []byte {
	var b bytes.Buffer
	b.WriteString(`# Configuration reference

<!-- Generated by go run ./tools/gendocs from internal/config/config.go. Do not edit by hand. -->

LANLeecher reads one YAML file, given by ` + "`--config`" + ` or ` + "`LANLEECHER_CONFIG`" + ` (default
` + "`/etc/lanleecher/config.yaml`" + `). Switches, ports, users and API tokens are not configured here;
they live in the database and are managed in the web UI.

- Relative paths are relative to the directory of the configuration file.
- Durations use Go syntax: ` + "`30s`, `10m`, `1h30m`" + `.
- Unknown keys are ignored. For editor validation, point your YAML language server at
  [config.schema.json](config.schema.json).
- Changes take effect after a restart (` + "`sudo systemctl restart lanleecher`" + `).

An annotated example is in [configs/lanleecher.example.yaml](../configs/lanleecher.example.yaml).
`)
	var section func(title string, fs []field, prefix string)
	section = func(title string, fs []field, prefix string) {
		fmt.Fprintf(&b, "\n## %s\n\n| Key | Type | Default | Description |\n| --- | --- | --- | --- |\n", title)
		var nested []field
		for _, f := range fs {
			if f.Fields != nil {
				nested = append(nested, f)
				continue
			}
			doc := f.Doc
			if len(f.Enum) > 0 {
				doc += " Allowed: " + "`" + strings.Join(f.Enum, "`, `") + "`."
			}
			fmt.Fprintf(&b, "| `%s%s` | %s | `%s` | %s |\n", prefix, f.Key, f.Type, formatDefault(f.Default),
				strings.ReplaceAll(doc, "|", "\\|"))
		}
		for _, n := range nested {
			title := "`" + prefix + n.Key + "`"
			if n.Doc != "" {
				title += " – " + strings.TrimSuffix(n.Doc, ".")
			}
			section(title, n.Fields, prefix+n.Key+".")
		}
	}
	section("Top level", fields, "")
	return b.Bytes()
}

func configSchema(fields []field) ([]byte, error) {
	var object func(fs []field) map[string]any
	object = func(fs []field) map[string]any {
		props := map[string]any{}
		for _, f := range fs {
			p := map[string]any{}
			if f.Doc != "" {
				p["description"] = f.Doc
			}
			switch f.Type {
			case "string":
				p["type"] = "string"
			case "int":
				p["type"] = "integer"
			case "float":
				p["type"] = "number"
			case "bool":
				p["type"] = "boolean"
			case "duration":
				p["type"] = "string"
				p["pattern"] = `^([0-9]+(\.[0-9]+)?(ns|us|µs|ms|s|m|h))+$`
			case "[]string":
				p["type"] = "array"
				items := map[string]any{"type": "string"}
				if len(f.Enum) > 0 {
					items["enum"] = f.Enum
				}
				p["items"] = items
			default:
				p = object(f.Fields)
				if f.Doc != "" {
					p["description"] = f.Doc
				}
			}
			if f.Type == "string" && len(f.Enum) > 0 {
				p["enum"] = f.Enum
			}
			if f.Fields == nil {
				switch d := f.Default.(type) {
				case time.Duration:
					p["default"] = formatDefault(d)
				case string:
					if d != "" {
						p["default"] = d
					}
				default:
					p["default"] = d
				}
			}
			props[f.Key] = p
		}
		return map[string]any{"type": "object", "additionalProperties": false, "properties": props}
	}
	schema := object(fields)
	schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
	schema["$id"] = "https://github.com/lan-dot-party/LANLeecher/blob/main/docs/config.schema.json"
	schema["title"] = "LANLeecher config.yaml"
	out, err := json.MarshalIndent(schema, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}
