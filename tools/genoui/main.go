// Command genoui builds internal/oui/oui.txt.gz from the IEEE registries
// MA-L (24-bit), MA-M (28-bit) and MA-S (36-bit). Run it from the repository
// root now and then to refresh the vendor names:
//
//	go run ./tools/genoui                 # download from standards-oui.ieee.org
//	go run ./tools/genoui -dir ./csv      # use downloaded oui.csv, mam.csv, oui36.csv
//
// The output has one line per assignment: hex prefix (6, 7 or 9 digits), a
// tab and the organization name, sorted, gzip-compressed without a timestamp
// so the file only changes when the data does.
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

var registries = []struct {
	file   string
	url    string
	digits int
}{
	{"oui.csv", "https://standards-oui.ieee.org/oui/oui.csv", 6},
	{"mam.csv", "https://standards-oui.ieee.org/oui28/mam.csv", 7},
	{"oui36.csv", "https://standards-oui.ieee.org/oui36/oui36.csv", 9},
}

func main() {
	dir := flag.String("dir", "", "read the CSV files from this directory instead of downloading them")
	out := flag.String("out", "internal/oui/oui.txt.gz", "output file")
	flag.Parse()

	entries := map[string]string{}
	for _, reg := range registries {
		data, err := read(*dir, reg.file, reg.url)
		if err != nil {
			log.Fatalf("%s: %v", reg.file, err)
		}
		n, err := parse(data, reg.digits, entries)
		if err != nil {
			log.Fatalf("%s: %v", reg.file, err)
		}
		fmt.Printf("%s: %d assignments\n", reg.file, n)
	}
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var buf bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	zw.Name = "oui.txt" // no ModTime: reproducible output
	fmt.Fprintf(zw, "# IEEE MA-L, MA-M and MA-S assignments, generated by tools/genoui on %s\n",
		time.Now().UTC().Format("2006-01-02"))
	for _, k := range keys {
		fmt.Fprintf(zw, "%s\t%s\n", k, entries[k])
	}
	if err := zw.Close(); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s: %d prefixes, %d bytes\n", *out, len(keys), buf.Len())
}

func read(dir, file, url string) ([]byte, error) {
	if dir != "" {
		return os.ReadFile(filepath.Join(dir, file))
	}
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "LANLeecher tools/genoui")
	resp, err := (&http.Client{Timeout: 2 * time.Minute}).Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP %d", resp.StatusCode)
	}
	return io.ReadAll(resp.Body)
}

// parse reads "Registry,Assignment,Organization Name,Organization Address".
func parse(data []byte, digits int, into map[string]string) (int, error) {
	r := csv.NewReader(bytes.NewReader(data))
	r.FieldsPerRecord = -1
	rows, err := r.ReadAll()
	if err != nil {
		return 0, err
	}
	n := 0
	for i, row := range rows {
		if i == 0 || len(row) < 3 {
			continue
		}
		prefix := strings.ToUpper(strings.TrimSpace(row[1]))
		name := strings.Join(strings.Fields(row[2]), " ")
		if len(prefix) != digits || name == "" {
			continue
		}
		into[prefix] = name
		n++
	}
	return n, nil
}
